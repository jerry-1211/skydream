def get_holidays_for_month(year, month):
    """해당 월의 공휴일 dict 반환: {day_number: holiday_name}"""
    result = {}
    for d, name in HOLIDAYS.items():
        if d.year == year and d.month == month:
            result[d.day] = name
    return result
